CREATE TABLE IF NOT EXISTS brand_narratives (
    id CHAR(36) NOT NULL PRIMARY KEY,
    client_id CHAR(36) NOT NULL,
    archetype VARCHAR(32) NOT NULL,
    doel TEXT NOT NULL,
    foe TEXT NOT NULL,
    spanning TEXT NOT NULL,
    mechanisme TEXT NOT NULL,
    geloofwaardigheidstest TEXT NOT NULL,
    verboden_logica JSON NOT NULL,
    bewijsvelden JSON NOT NULL,
    tone_of_behaviour TEXT NOT NULL,
    woorden_die_passen JSON NOT NULL,
    woorden_die_niet_passen JSON NOT NULL,
    goede_voorbeelden JSON NOT NULL,
    zwakke_voorbeelden JSON NOT NULL,
    contextprofiel VARCHAR(32) NOT NULL,
    default_platforms JSON NULL,
    target_post_volume_per_month INT NULL,
    version INT NOT NULL DEFAULT 1,
    is_current TINYINT(1) NOT NULL DEFAULT 1,
    created_by CHAR(36) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_brand_narratives_client (client_id),
    KEY idx_brand_narratives_current (client_id, is_current)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

