    scored_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(32) NOT NULL,
    contentrol VARCHAR(32) NULL,
    contentrol_motivation TEXT NULL,
    bc_archetype_fit DECIMAL(3,1) NULL,
    bc_doel_fit DECIMAL(3,1) NULL,
    bc_tegenkracht_fit DECIMAL(3,1) NULL,
    bc_spanning DECIMAL(3,1) NULL,
    bc_mechanisme_proof DECIMAL(3,1) NULL,
    bc_distinctiviteit DECIMAL(3,1) NULL,
    brand_contribution_score DECIMAL(3,1) NULL,
    brand_consistency_score DECIMAL(3,1) NULL,
    brand_consistency_notes TEXT NULL,
    architecture_risk_score DECIMAL(3,1) NULL,
    architecture_risk_flags JSON NULL,
    long_term_value DECIMAL(3,1) NULL,
    short_term_value DECIMAL(3,1) NULL,
    content_weight DECIMAL(4,3) NOT NULL DEFAULT 1.000,
    content_weight_method_version VARCHAR(16) NOT NULL DEFAULT 'cw_v1_1',
