CREATE TABLE IF NOT EXISTS testset_blind_scores (
  id CHAR(36) NOT NULL,
  stap VARCHAR(32) NOT NULL,
  code VARCHAR(8) NOT NULL,
  scorer VARCHAR(32) NOT NULL,
  q_clear_claim TINYINT NOT NULL,
  q_concrete TINYINT NOT NULL,
  q_brand TINYINT NOT NULL,
  q_dutch TINYINT NOT NULL,
  q_would_post TINYINT NOT NULL,
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_testset_blind_score (stap, code, scorer)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
